export const localizeAdminText = (value, locale = 'en', isError = false) => {
  const text = String(value ?? '');
  if (locale !== 'tl' || !text) return text;
  if (TL_ADMIN_TEXT[text]) return TL_ADMIN_TEXT[text];

  const patterns = [
    [/^(\d+) this week$/, '$1 ngayong linggo'], [/^(\d+) in directory$/, '$1 sa talaan'],
    [/^(\d+) submitted today$/, '$1 ang isinumite ngayon'], [/^(\d+) total advisories$/, '$1 kabuuang advisory'],
    [/^(\d+) resident profiles$/, '$1 profile ng residente'], [/^(\d+) posts stored$/, '$1 post ang nakaimbak'],
    [/^(\d+)% of pending work$/, '$1% ng nakabinbing gawain'], [/^(\d+) file\(s\)$/, '$1 file'],
    [/^Pending confirmation: (.+)$/, 'Naghihintay ng kumpirmasyon: $1'],
    [/^Request (.+)ed successfully$/, 'Matagumpay na naisagawa ang aksyon sa kahilingan.'],
    [/^(.+) deleted successfully\.$/, 'Matagumpay na tinanggal ang $1.']
  ];
  for (const [pattern, replacement] of patterns) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return isError ? 'Hindi nakumpleto ang operasyon. Pakisubukan muli.' : text;
};

export const localizeAdminStructure = (value, locale = 'en') => {
  if (Array.isArray(value)) return value.map((item) => localizeAdminStructure(item, locale));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localizeAdminStructure(item, locale)]));
  }
  return typeof value === 'string' ? localizeAdminText(value, locale) : value;
};
